export function applyPhoneCopy(instance: I18n): void {
  LANGUAGES.forEach((lang, index) => {
    const advice = WATER_COPY[lang].advice;
    const balance = instance.getResource(lang, 'devices', 'environment.water.balance');
    const rainToday = instance.getResource(lang, 'devices', 'zone.water.rainToday');
    for (const [key, text] of Object.entries(DEVICE_KEYS)) {
      instance.addResource(lang, 'devices', key, TEXT[text][index], {silent: true});
    }
    for (const key of ['drivenByBalance', 'drivenByWaterBalanceFromWeather', 'drivenByWaterBalanceFromStation']) {
      instance.addResource(lang, 'devices', `zone.water.${key}`, advice, {silent: true});
    }
    instance.addResource(lang, 'devices', 'environment.water.balance', `${balance} · ${advice}`, {silent: true});
    instance.addResource(lang, 'devices', 'zone.water.subtitle', `${rainToday} · ${TEXT.irrigationMeter[index]}`, {silent: true});
    instance.addResource(lang, 'settings', 'timeZoneInvalid', TEXT.invalidTimezone[index], {silent: true});
    const tensionSample = instance.getResource(lang, 'settings', 'swtSample');
    instance.addResource(lang, 'settings', 'swtSample', `${tensionSample} · ${TEXT.illustrative[index]}`, {silent: true});
    instance.addResource(lang, 'common', 'analysis.aggregation.help', TEXT.aggregationHelp[index], {silent: true});
    instance.addResourceBundle(lang, 'common', {
      farmSim: {
        game_refused: TEXT.refused[index],
        game_tier: TEXT.tier[index],
        flowMeterHeading: TEXT.meterHeading[index],
      },
    }, true, true);
  });
}

