#!/usr/bin/env node
'use strict';
// The existing declared loader binding carries a lazy, self-contained fallback.
// No optional package or extra file is needed to execute it after a load fault.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {ENTRIES}=require('./lib/valve-ingress-x2-renderer');
const ROOT=path.resolve(__dirname,'..');
const MARKER='// BEGIN GENERATED X2 INGRESS FALLBACK';
function generated(profile){
 const dir=path.join(ROOT,`conf/full_raspberrypi_bcm27xx_${profile}/files/usr/share/node-red/osi-command-ingress`);
 const functions=[require(path.join(dir,'command-routing')).routeNonValveCommand,...ENTRIES.map(([_id,entry,file])=>require(path.join(dir,file))[entry])];
 const factory=functions.map(fn=>fn.toString()).join('\n\n')+'\nreturn { routeNonValveCommand, '+ENTRIES.map(([_id,entry])=>entry).join(', ')+' };';
 return `${MARKER}\n// Generated by scripts/generate-valve-ingress-x2-fallback.js; checked in CI.\nconst x2IngressFactory = ${JSON.stringify(factory)};\nlet x2IngressFallback;\nmodule.exports.invokeCommandIngress = function(entry, msg, deps) {\n  if (!x2IngressFallback) x2IngressFallback = new Function(x2IngressFactory)();\n  if (typeof x2IngressFallback[entry] !== 'function') throw new Error('Unknown ingress entry: ' + entry);\n  return x2IngressFallback[entry](msg, deps);\n};\n// END GENERATED X2 INGRESS FALLBACK\n`;
}
function main(){
 assert.ok(process.argv.slice(2).every(arg=>arg==='--write'),'unknown fallback generation option');
 for(const profile of ['bcm2712','bcm2709']){
  const file=path.join(ROOT,`conf/full_raspberrypi_bcm27xx_${profile}/files/usr/share/node-red/osi-lib/index.js`);
  const current=fs.readFileSync(file,'utf8'),prefix=current.split(MARKER)[0].trimEnd()+'\n\n',expected=prefix+generated(profile);
  if(process.argv.includes('--write'))fs.writeFileSync(file,expected);
  else assert.equal(current,expected,'generated fallback drift: '+profile);
 }
 console.log('X2 bundled fallback matches all entry implementations on both profiles');
}
if(require.main===module)main();
module.exports={generated,MARKER};
