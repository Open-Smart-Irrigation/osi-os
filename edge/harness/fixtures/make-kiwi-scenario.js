#!/usr/bin/env node
'use strict';
// Builds scenarios/060-kiwi-ingest.json: synthetic KIWI uplinks as ChirpStack
// v4 would publish them, with `object` produced by the SHIPPED codec
// (codecs/tektelic_agriculture_decoder.js), never written by hand.
// Deterministic: same input, same file. Example EUIs only.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const ROOT = path.resolve(__dirname, '../../..');
const CODEC = path.join(ROOT, 'conf/full_raspberrypi_bcm27xx_bcm2712/files/usr/share/node-red/codecs/tektelic_agriculture_decoder.js');
const sandbox = {}; vm.createContext(sandbox); vm.runInContext(fs.readFileSync(CODEC, 'utf8'), sandbox);
const decode = (fPort, bytes) => JSON.parse(JSON.stringify(sandbox.decodeUplink({ fPort, bytes })));

const COUNT = Number(process.argv[2] || 520);
const CLAIMED = 'A840410000000001', UNCLAIMED = 'A840410000000002', GATEWAY = '0016c001f1000001';
let seed = 20261123;
const rand = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };
const u16 = (v) => [(v >> 8) & 0xff, v & 0xff];
const s16 = (v) => u16(v < 0 ? v + 65536 : v);

function frame(i) {
  const kind = i % 97 === 13 ? 'empty' : i % 89 === 7 ? 'truncated' : i % 83 === 5 ? 'foreign-port' : i % 41 === 3 ? 'battery-only' : 'full';
  if (kind === 'empty') return { kind, fPort: 10, bytes: [] };
  if (kind === 'truncated') return { kind, fPort: 10, bytes: [0x0b, 0x67] };
  if (kind === 'foreign-port') return { kind, fPort: 99, bytes: [0x01, 0x02] };
  if (kind === 'battery-only') return { kind, fPort: 10, bytes: [0x00, 0xba, 0x40 + Math.floor(rand() * 40)] };
  const f5 = 300 + Math.floor(rand() * 6500), f6 = 300 + Math.floor(rand() * 6500);
  const light = Math.floor(rand() * 5000), temp = Math.round((rand() * 50 - 10) * 10), rh = Math.floor(rand() * 200);
  return { kind, fPort: 10, bytes: [0x05, 0x04, ...u16(f5), 0x06, 0x04, ...u16(f6), 0x09, 0x65, ...u16(light), 0x0b, 0x67, ...s16(temp), 0x0b, 0x68, rh, 0x00, 0xba, 0x40 + Math.floor(rand() * 40)] };
}

// All uplink times lie in the past: future times are clamped to the clock, which made reads time-dependent.
const base = Date.UTC(2026, 10, 1, 0, 0, 0);
const uplinks = [];
const kinds = {};
let previous = null;
for (let i = 0; i < COUNT; i++) {
  const eui = i % 10 === 9 ? UNCLAIMED : CLAIMED;
  // Every 50th message repeats the previous one exactly (a broker redelivery).
  if (i % 50 === 49 && previous) { uplinks.push({ ...previous, note: 'redelivery' }); kinds.redelivery = (kinds.redelivery || 0) + 1; continue; }
  const f = frame(i);
  kinds[f.kind] = (kinds[f.kind] || 0) + 1;
  const decoded = decode(f.fPort, f.bytes);
  const time = new Date(base + i * 15 * 60 * 1000).toISOString();
  const payload = {
    deduplicationId: '00000000-0000-4000-8000-' + String(i + 1).padStart(12, '0'),
    time,
    deviceInfo: { tenantId: '00000000-0000-4000-8000-00000000aaaa', tenantName: 'synthetic', applicationId: 'synthetic-sensors-app', applicationName: 'Sensors',
      deviceProfileId: 'ae4194a5-56f8-4ca0-a129-8ad958505e1e', deviceProfileName: 'KIWI', deviceName: eui === CLAIMED ? 'kiwi-1' : 'kiwi-2', devEui: eui.toLowerCase(), tags: {} },
    devAddr: '01020304', adr: true, dr: 5, fCnt: i + 1, fPort: f.fPort, confirmed: false,
    data: Buffer.from(f.bytes).toString('base64'),
    rxInfo: [{ gatewayId: GATEWAY, uplinkId: i + 1, rssi: -60 - (i % 40), snr: 7.5 - (i % 10), channel: i % 8, location: {}, context: 'AAAAAA==', crcStatus: 'CRC_OK' }],
    txInfo: { frequency: 868100000 + (i % 8) * 200000, modulation: { lora: { bandwidth: 125000, spreadingFactor: 7, codeRate: 'CR_4_5' } } },
  };
  // ChirpStack omits `object` when the codec reports errors.
  if (!(decoded.errors && decoded.errors.length)) payload.object = decoded.data;
  const msg = { topic: 'application/synthetic-sensors-app/device/' + eui.toLowerCase() + '/event/up', payload };
  uplinks.push(msg); previous = msg;
}
const now = '2026-11-01T00:00:00.000Z';
const scenario = {
  name: 'kiwi-ingest',
  description: `${COUNT} synthetic KIWI uplinks (codec-decoded): ${JSON.stringify(kinds)}. 90% to a claimed sensor, 10% to an unknown one. Generated by fixtures/make-kiwi-scenario.js.`,
  steps: [
    { id: 'register', http: { method: 'POST', path: '/auth/register', body: { username: 'farmer', password: 'synthetic-pass-1' } } },
    { id: 'login', http: { method: 'POST', path: '/auth/login', body: { username: 'farmer', password: 'synthetic-pass-1' } }, capture: { token: 'json.token' } },
    { id: 'claim-sensor', why: 'a claimed KIWI with no ChirpStack registration; the release smoke sets devices up the same way',
      sql: `INSERT INTO devices(deveui,name,type_id,user_id,created_at,updated_at,claimed_at,current_state) VALUES ('${CLAIMED}','kiwi-1','KIWI_SENSOR',1,'${now}','${now}','${now}',NULL)` },
    { id: 'uplinks', uplinks, gapMs: 5 },
    { id: 'devices-after', http: { method: 'GET', path: '/api/devices', auth: 'token' } },
  ],
};
const out = path.join(__dirname, '../scenarios/060-kiwi-ingest.json');
fs.writeFileSync(out, JSON.stringify(scenario, null, 1) + '\n');
console.log('wrote', out, uplinks.length, 'uplinks', JSON.stringify(kinds));
